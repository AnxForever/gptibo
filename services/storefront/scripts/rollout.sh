#!/bin/sh
# Build and roll out the storefront on the deployment host.
#
#   ./scripts/rollout.sh [release-version]
#
# Run from the deployed checkout (by default /opt/anx/services/storefront).
# The version defaults to today's date and tags the built image. Pair it with
# scripts/deploy.sh, which pushes the tree here and then calls this.
#
# Step 4 regenerates the nginx security-header snippet from the built
# dist/_headers, so the policy nginx sends can never drift from the one the
# web build was written against. Edit the build output, not that snippet.
set -e
cd "$(dirname "$0")/.."

RELEASE=${1:-$(date +%Y.%m.%d)}
export RELEASE_VERSION="$RELEASE"
step() { printf '\n[%s] %s\n' "$(date +%H:%M:%S)" "$1"; }

step "1/6 构建镜像 (release=$RELEASE)"
docker compose build

step "2/6 迁移数据库"
docker compose --profile maintenance run --rm maintenance migrate

step "3/6 授权运行角色"
docker compose --profile maintenance run --rm maintenance grant-runtime

step "4/6 同步 nginx 安全头（策略来自 dist/_headers，两侧永不漂移）"
if [ -f /opt/anx/dist/_headers ]; then
  grep -h "^  Content-Security-Policy:" /opt/anx/dist/_headers | sed 's/^  Content-Security-Policy: *//' > /tmp/anx-csp.txt
  if [ -s /tmp/anx-csp.txt ]; then
    {
      echo "# Generated from dist/_headers plus the transport protections."
      echo "# Regenerated by scripts/rollout.sh on every rollout — edit the build output, not this file."
      echo 'add_header Strict-Transport-Security "max-age=31536000" always;'
      echo 'add_header X-Content-Type-Options    "nosniff" always;'
      echo 'add_header X-Frame-Options           "DENY" always;'
      echo 'add_header Referrer-Policy           "strict-origin-when-cross-origin" always;'
      echo 'add_header Permissions-Policy        "camera=(), microphone=(), geolocation=(), payment=()" always;'
      echo 'add_header X-Robots-Tag              "noindex, nofollow" always;'
      printf 'add_header Content-Security-Policy "%s" always;\n' "$(cat /tmp/anx-csp.txt)"
    } > /etc/nginx/snippets/anx-headers.conf
    if nginx -t >/dev/null 2>&1; then
      systemctl reload nginx && echo "  安全头已同步并重载 nginx"
    else
      echo "  nginx 配置校验失败，保留原有片段" >&2
      exit 1
    fi
  fi
  rm -f /tmp/anx-csp.txt
fi

step "5/6 启动服务"
docker compose up -d --wait api worker

step "6/6 健康检查"
curl -fsS http://127.0.0.1:8093/healthz; echo
docker compose ps --format "  {{.Name}}  {{.Status}}"
printf '\n部署完成 release=%s\n' "$RELEASE"
